function findTopicHook(title, phaseFrame) {
  for (const [pattern, hook] of TOPIC_HOOKS) {
    if (pattern.test(title)) {
      return hook;
    }
  }
  return phaseFrame.lead;
}

function makeDatabaseCopy({ module, title, order, code, changes, project, analysis }) {
  const frame = PHASE_FRAMES[module.id] || PHASE_FRAMES["phase-0-foundations"];
  const topicHook = findTopicHook(title, frame);

  const summary = topicHook + " في هذا الدرس نختبر أثر «" + title + "» عمليًا داخل مثال " + project + ".";
  const concept = topicHook + " حول موضوع «" + title + "»، لا نحاول حسم كل التفاصيل دفعة واحدة؛ نحدد الحقيقة الأساسية أمامنا ثم نختبر كيف ينعكس القرار داخل المثال.";
  const whyUse = frame.why + " في سياق «" + title + "»، تجاهل هذا الفهم يظهر لاحقًا كبيانات متناقضة أو تقارير تحتاج مراجعة يدوية.";
  const browserMechanics = frame.mechanics + (analysis
    ? " وبما أننا في مرحلة التحليل، يوثق المحرر القرار في تعليق واضح بجانب استعلام مختصر لنربط التفكير بالنتيجة."
    : " عند التشغيل ترى كيف يتأثر سلوك الاستعلام أو المخطط مباشرة بالقرار الذي اتخذته.");

  const breakdown = [
    "السؤال المحرك: " + topicHook,
    "نطاق القرار في «" + title + "» ضمن سياق " + project + " مع إبقاء المجهول واضحًا.",
    "الأثر المتوقع: " + frame.stepCue
  ];

  const steps = changes.map(function (change, stepIndex) {
    const stepNo = stepIndex + 1;
    const isFinalStep = stepIndex === changes.length - 1;
    const objective = stepNo === 1
      ? "تمييز المدخل الأساسي لقرار «" + title + "» قبل إضافة تفاصيل أخرى."
      : isFinalStep
        ? "تثبيت الصيغة النهائية القابلة للاختبار والتأكد من تطابقها مع قاعدة العمل."
        : "نقل الملاحظة إلى صياغة أوضح تبرز أثر القرار عند التنفيذ.";

    const instruction = analysis
      ? "لاحظ موضع `" + change.from + "` ثم حدّثه في السطر المعني ليعكس قرار «" + change.title + "»، وشغّل للمقارنة."
      : "عدّل الجزء `" + change.from + "` إلى الصيغة المطلوبة لخطوة «" + change.title + "»، ثم راقب تغيّر النتيجة.";

    const benefit = stepNo === 1
      ? "أثر الخطوة: صار السؤال في «" + title + "» محددًا في سطر واضح بدل بقائه افتراضًا غير مفحوص."
      : isFinalStep
        ? "أثر الخطوة: اكتمل الدليل العملي للدرس بحيث يسهل اختباره وشرحه ضمن " + project + "."
        : "أثر الخطوة: تقلص غموض المثال وأصبح من السهل رؤية ما يتغير عند الاختبار.";

    const tier1 = stepNo === 1
      ? "تأمل الكود الحالي حول `" + change.from + "`: ما الكلمة أو الرمز الذي يحول المشهد العام لـ «" + title + "» إلى خطوة محددة؟"
      : "انظر إلى السطر الذي عدلته للتو؛ " + frame.stepCue;
    const tier2 = frame.stepCue + " هل حددت البديل الأدق لموضع `" + change.from + "`؟";
    const tier3 = "قرّب التعديل نحو هذه الصياغة: " + change.to;
    const tier4 = "الحل الدقيق للخطوة هو: " + change.to;

    return {
      objective,
      instruction,
      benefit,
      hints: [tier1, tier2, tier3, tier4]
    };
  });

  const bugRepair = {
    question: "قبل اعتماد مثال «" + title + "»، أي خلل صامت قد يفسد النتيجة رغم عدم ظهور خطأ شكلي؟",
    explanation: "الأهم في «" + title + "» هو ربط الصياغة بقاعدة العمل وحدودها؛ " + frame.why
  };

  return {
    summary,
    concept,
    whyUse,
    browserMechanics,
    breakdown,
    steps,
    bugRepair
  };
}

